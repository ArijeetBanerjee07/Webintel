// Precompute bounding boxes for O(1) broadphase rejection
interface BoundingBox {
  minLat: number;
  maxLat: number;
  minLon: number;
  maxLon: number;
}

const BOUNDING_BOXES: BoundingBox[] = ALL_CONTINENTS.map((polygon) => {
  let minLat = 90;
  let maxLat = -90;
  let minLon = 180;
  let maxLon = -180;

  for (let i = 0; i < polygon.length; i++) {
    const [lat, lon] = polygon[i];
    if (lat < minLat) minLat = lat;
    if (lat > maxLat) maxLat = lat;
    if (lon < minLon) minLon = lon;
    if (lon > maxLon) maxLon = lon;
  }

  return { minLat, maxLat, minLon, maxLon };
});

/**
 * Standard ray-casting point-in-polygon algorithm
 */
function pointInPolygon(lat: number, lon: number, poly: [number, number][]): boolean {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const xi = poly[i][1];
    const yi = poly[i][0];
    const xj = poly[j][1];
    const yj = poly[j][0];

    const intersect =
      yi > lat !== yj > lat &&
      lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;

    if (intersect) inside = !inside;
  }
  return inside;
}

/**
 * Highly optimized land check combining broadphase AABB filtering
 * and narrowphase ray casting.
 */
export function isLandCoordinate(lat: number, lon: number): boolean {
  for (let i = 0; i < ALL_CONTINENTS.length; i++) {
    const box = BOUNDING_BOXES[i];
    if (
      lat < box.minLat ||
      lat > box.maxLat ||
      lon < box.minLon ||
      lon > box.maxLon
    ) {
      continue;
    }

    if (pointInPolygon(lat, lon, ALL_CONTINENTS[i])) {
      return true;
    }
  }

  return false;
}

