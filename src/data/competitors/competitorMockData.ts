function addCompetitorDetails(
  records: Omit<
    CompetitorRecord,
    | "referringDomains"
    | "topPages"
    | "contentThemes"
    | "technologyStack"
    | "keywordRankingDistribution"
    | "backlinkProfile"
    | "sharedKeywords"
    | "serpOverlap"
    | "category"
  >[],
  categories: string[],
  sharedKeywordSet: CompetitorRecord["sharedKeywords"],
  serpOverlapSet: CompetitorRecord["serpOverlap"]
): CompetitorRecord[] {
  return records.map((competitor, index) => {
    const slug = competitor.domain.split(".")[0];

    const totalBacklinks = 1600 + index * 320;

    const dofollowBacklinks = Math.round(
      totalBacklinks * (0.72 - index * 0.01)
    );

    const nofollowBacklinks = totalBacklinks - dofollowBacklinks;

    return {
      ...competitor,

      // Illustrative mock values
      referringDomains: 180 + index * 47,

      topPages: [
        {
          url: `https://${competitor.domain}/`,
          estimatedTraffic: 5200 + index * 400,
          rankingKeywords: 350 + index * 50,
          averagePosition: 8 + index,
        },
        {
          url: `https://${competitor.domain}/blog/${slug}-guide`,
          estimatedTraffic: 3200 + index * 250,
          rankingKeywords: 220 + index * 30,
          averagePosition: 12 + index,
        },
        {
          url: `https://${competitor.domain}/products/${slug}`,
          estimatedTraffic: 2100 + index * 180,
          rankingKeywords: 150 + index * 20,
          averagePosition: 15 + index,
        },
      ],

      contentThemes: themeSets[index % themeSets.length],

      technologyStack: technologySets[index % technologySets.length],

      keywordRankingDistribution: {
        top3: 15 + index * 4,
        positions4to10: 30 + index * 6,
        positions11to20: 45 + index * 8,
        positions21to50: 60 + index * 10,
        positions51to100: 80 + index * 12,
      },

      backlinkProfile: {
        totalBacklinks,
        dofollowBacklinks,
        nofollowBacklinks,
      },

      sharedKeywords: sharedKeywordSet.map((keyword) => ({
  ...keyword,
  searchVolume: keyword.searchVolume + index * 100,
  competitorRanking: keyword.competitorRanking + index,
})),

     serpOverlap: serpOverlapSet.map((keyword) => ({
  ...keyword,
  searchVolume: keyword.searchVolume + index * 80,
  competitorRanking: keyword.competitorRanking + index,
})),

      // Assign category based on the selected target website
      category: categories[index],
    };
  });
}


